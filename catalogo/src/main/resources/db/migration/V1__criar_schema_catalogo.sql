CREATE UNIQUE INDEX IF NOT EXISTS uk_compra_usuario_idempotency
    ON compras (usuario_id, idempotency_key);
CREATE INDEX IF NOT EXISTS ix_eventos_outbox_pendentes
    ON eventos_outbox (publicado_em, id);
